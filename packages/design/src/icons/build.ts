// The Icon set -> the store's glyphs: one JSX element per variant (`name=<kebab-case>`), the inside of a 24 × 24
// <svg>. A port of Atope's icons script to the web: plain svg elements instead of react-native-svg, and no
// <svg> per glyph, so the hand-written Icon draws the frame (size, aria-hidden) once.
//
// The SVG is converted here, at build time, so nothing is parsed at run time. Each glyph is drawn in one colour
// (bound to a Theme role in FigCraft); it becomes currentColor, so the Icon's text colour draws it. A clip to the
// whole frame does nothing inside a 24 × 24 viewBox and is dropped; any other clip id gets the glyph's name, so
// inline SVGs on one page don't share ids.

/** Where the glyphs go, and the set they come from. */
export type IconsConfig = { set: string; output: string }

type Node = { tag: string; attrs: Record<string, string>; children: Node[] }

const SIZE = 24
const FRAME_CLIP = `M0 0L${SIZE} 0L${SIZE} ${SIZE}L0 ${SIZE}Z`
const ELEMENTS = new Set(['g', 'path', 'defs', 'clipPath', 'circle', 'ellipse', 'line', 'polygon', 'polyline', 'rect'])
/** What FigCraft puts on the root <svg>; the Icon's own <svg> carries the frame instead. */
const ROOT_ATTRIBUTES = new Set(['width', 'height', 'viewBox', 'fill', 'xmlns'])
const HEX = /^#[0-9A-Fa-f]{6}$/

/** The glyph file from one SVG per variant name. No glyphs, no file: the store has no Icon yet. */
export function buildIcons(svgs: Map<string, string>, config: IconsConfig): Map<string, string> {
  if (svgs.size === 0) return new Map()
  const problems: string[] = []
  const glyphs = [...svgs.keys()].sort().map((name) => {
    const fail = (message: string) => problems.push(`${name}: ${message}`)
    const svg = parse(svgs.get(name) ?? '', fail)
    if (svg?.tag !== 'svg') {
      fail('not an <svg>')
      return ''
    }
    if (svg.attrs.viewBox !== `0 0 ${SIZE} ${SIZE}`) {
      fail(`viewBox ${svg.attrs.viewBox}, not 0 0 ${SIZE} ${SIZE} (clip the variant to its frame in FigCraft)`)
    }
    for (const key of Object.keys(svg.attrs)) if (!ROOT_ATTRIBUTES.has(key)) fail(`<svg ${key}> is not kept`)
    if (svg.attrs.fill && svg.attrs.fill !== 'none')
      fail(`<svg fill="${svg.attrs.fill}">; the Icon's frame is unfilled`)
    const colours = new Set<string>()
    walk(svg, (node) => {
      for (const key of ['fill', 'stroke']) if (HEX.test(node.attrs[key] ?? '')) colours.add(node.attrs[key] ?? '')
    })
    if (colours.size > 1) fail(`${colours.size} colours (${[...colours].join(', ')}); a glyph is one colour`)
    walk(svg, (node) => {
      if (node.tag !== 'svg' && !ELEMENTS.has(node.tag)) fail(`<${node.tag}> is not an svg element a glyph may use`)
    })
    const body = tidy(svg, name).children
    const lines =
      body.length === 1 && body[0] ? jsx(body[0], 2) : ['    <>', ...body.flatMap((node) => jsx(node, 3)), '    </>']
    return [`  ${keyLiteral(name)}: (`, ...lines, '  ),'].join('\n')
  })
  if (problems.length) throw new Error(`${config.set} can't be generated:\n  ${problems.join('\n  ')}`)

  const source = [
    `// Generated by @proteus/design from the FigCraft component set "${config.set}". Do not edit: change the design file, then run icons:export.`,
    "// Each glyph is the inside of a 24 × 24 <svg>; icon.tsx draws the frame, and its text colour is the glyph's (currentColor).",
    '',
    'export const glyphs = {',
    ...glyphs,
    '}',
    '',
    `/** A glyph of the design file's ${config.set} set: the \`name\` prop of the store's Icon. */`,
    'export type IconName = keyof typeof glyphs',
    '',
  ].join('\n')
  return new Map([[config.output, source]])
}

/** Drops the frame clip, empty <defs> and bare <g>s; names the other clips after the glyph; colours become currentColor. */
function tidy(svg: Node, name: string): Node {
  const frameClips = new Set<string>()
  walk(svg, (node) => {
    const [only] = node.children
    if (node.tag === 'clipPath' && node.children.length === 1 && only?.attrs.d === FRAME_CLIP) {
      frameClips.add(node.attrs.id ?? '')
    }
  })
  const visit = (node: Node): Node => {
    const attrs = { ...node.attrs }
    const clip = /^url\(#(.+)\)$/.exec(attrs['clip-path'] ?? '')?.[1]
    if (clip && frameClips.has(clip)) delete attrs['clip-path']
    else if (clip) attrs['clip-path'] = `url(#${name}-${clip})`
    if (node.tag === 'clipPath') attrs.id = `${name}-${attrs.id}`
    for (const key of ['fill', 'stroke']) if (HEX.test(attrs[key] ?? '')) attrs[key] = 'currentColor'
    const children = node.children
      .filter((child) => !(child.tag === 'clipPath' && frameClips.has(child.attrs.id ?? '')))
      .map(visit)
      .flatMap((child) => {
        if (child.tag === 'defs' && child.children.length === 0) return []
        if (child.tag === 'g' && Object.keys(child.attrs).length === 0) return child.children
        return [child]
      })
    return { tag: node.tag, attrs, children }
  }
  return visit(svg)
}

function jsx(node: Node, depth: number): string[] {
  const pad = '  '.repeat(depth)
  const props = Object.entries(node.attrs).map(([key, value]) => ` ${camel(key)}="${value}"`)
  const open = `${pad}<${node.tag}${props.join('')}`
  if (node.children.length === 0) return [`${open} />`]
  return [`${open}>`, ...node.children.flatMap((child) => jsx(child, depth + 1)), `${pad}</${node.tag}>`]
}

// FigCraft writes plain SVG: elements and attributes, no text, no CDATA. Anything else is reported.
function parse(source: string, fail: (message: string) => void): Node | undefined {
  const top: Node = { tag: '', attrs: {}, children: [] }
  const stack = [top]
  const tags = /<(\/?)([A-Za-z][\w:-]*)((?:\s+[\w:-]+="[^"]*")*)\s*(\/?)>|([^<]+)|(<)/g
  for (const [, close, tag = '', attrs = '', selfClosing, text, stray] of source.trim().matchAll(tags)) {
    if (stray || text?.trim()) {
      // Text inside an element is the element's problem (a <text> is reported as an element); stray markup isn't.
      if (stray || stack.length === 1)
        fail(`unexpected content in the SVG: ${(stray ?? text ?? '').trim().slice(0, 40)}`)
      continue
    }
    if (text) continue
    if (close) {
      if (stack.pop()?.tag !== tag) {
        fail(`</${tag}> closes the wrong element`)
        return undefined
      }
      continue
    }
    const node: Node = {
      tag,
      attrs: Object.fromEntries(
        [...attrs.matchAll(/([\w:-]+)="([^"]*)"/g)].map(([, key = '', value = '']) => [key, value]),
      ),
      children: [],
    }
    stack.at(-1)?.children.push(node)
    if (!selfClosing) stack.push(node)
  }
  return top.children[0]
}

function walk(node: Node, visit: (node: Node) => void) {
  visit(node)
  for (const child of node.children) walk(child, visit)
}

const camel = (name: string) => name.replace(/[-:]([a-z])/g, (_, letter: string) => letter.toUpperCase())
const keyLiteral = (key: string) => (/^[A-Za-z_$][\w$]*$/.test(key) ? key : `'${key}'`)
