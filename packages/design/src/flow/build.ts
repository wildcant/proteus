// The flow map -> the store's navigation module (`flow.gen.ts`), and check:flow, which holds the map, the
// hand-written screen table and the route tree to each other. A port of Atope's flow script, for TanStack Router.
//
//   flow.gen.ts   per screen, per event: the transitions drawn on the map. Events that stay on their screen are
//                 kept: on the web they change the URL (search params, a drawer route), so they are links too.
//                 A target drawn as `./state` (STAY) is the current route, whichever renders the screen: the
//                 store links it as `to: '.'` with a search updater, so one screen covers several routes.
//   check:flow    every target is in the screen table; every screen on the map has a route there, and that
//                 route is in the tree; every route is some screen's, and every leaf route renders the screen
//                 its entry names (itself or through the layout above it: a drawer is a state of the screen it
//                 covers). A route is skipped by its shape alone: a component that renders only <Outlet />,
//                 or no component and a redirect in beforeLoad. Nothing is checked while the map has no flows.
import type { FlowSnapshot } from './snapshot.ts'

/** One route of the tree: its id, its parent's, its file (for messages) and its source. */
export type RouteNode = { id: string; parent: string | undefined; file: string; source: string }

/** The store's screen table, as check:flow reads it: `Screen` or `Screen/state` -> the route that renders it. */
export type ScreenTable = Record<string, { route: string }>

type Entry = { from: string; to: string; state: string; condition?: string }

/** The target screen of a transition that stays on the current route and changes only its search. */
export const STAY = '.'

const HEADER = [
  '// Generated by @proteus/design from the FigCraft `flows` page. Do not edit: change the design file, then run flow:export.',
  '// Per screen, per event: the transitions drawn on the map (from state, target screen and state, condition).',
]

export function buildFlow(snapshot: FlowSnapshot): string {
  const flow = transitionsByScreen(snapshot)
  const states = Object.fromEntries(Object.entries(snapshot.screens).map(([name, set]) => [name, set.states]))
  return [
    ...HEADER,
    '',
    '/** @public The states of each screen set: the variants a screen shows. */',
    `export const screenStates = ${objectLiteral(sorted(states), (list) => `[${list.map(quote).join(', ')}]`)} as const`,
    '',
    `export const flow = ${objectLiteral(sorted(flow), (events) =>
      objectLiteral(sorted(events), (list) => `[${list.map(entryLiteral).join(', ')}]`, 2),
    )} as const`,
    '',
  ].join('\n')
}

// Transitions grouped by source screen and event, checked against the screen sets' states, and deduplicated on
// (from, event, to, condition): one state may be drawn more than once.
function transitionsByScreen({ screens, flows }: FlowSnapshot) {
  const problems: string[] = []
  const byScreen: Record<string, Record<string, Entry[]>> = {}
  const seen = new Set<string>()
  const checkState = (where: string, screen: string, state: string) => {
    const set = screens[screen]
    if (!set) problems.push(`${where}: ${screen} is not a screen set`)
    else if (!set.states.includes(state)) problems.push(`${where}: ${screen} has no state ${state}`)
  }
  for (const { name, transitions } of flows) {
    for (const t of transitions) {
      checkState(name, t.from, t.fromState)
      // A STAY target is a state of the screen it is drawn from.
      checkState(name, t.to === STAY ? t.from : t.to, t.toState)
      const key = [t.from, t.fromState, t.event, t.to, t.toState, t.condition].join('|')
      if (seen.has(key)) continue
      seen.add(key)
      const events = byScreen[t.from] ?? {}
      byScreen[t.from] = events
      events[t.event] = [
        ...(events[t.event] ?? []),
        { from: t.fromState, to: t.to, state: t.toState, ...(t.condition ? { condition: t.condition } : {}) },
      ]
    }
  }
  if (problems.length) throw new Error(`flows can't be generated:\n  ${[...new Set(problems)].join('\n  ')}`)
  return byScreen
}

/** check:flow's findings: the map, the screen table and the route tree, against each other. */
export function routeProblems(snapshot: FlowSnapshot, table: ScreenTable, routes: RouteNode[]): string[] {
  if (snapshot.flows.length === 0) return []
  return [...mapProblems(snapshot, table), ...tableProblems(snapshot, table, routes), ...treeProblems(table, routes)]
}

/** Every target on the map is in the table, and every screen on the map has a route there. */
function mapProblems(snapshot: FlowSnapshot, table: ScreenTable) {
  // A STAY target needs no entry: it is the route the screen is already on.
  const transitions = snapshot.flows.flatMap((flow) => flow.transitions).filter((t) => t.to !== STAY)
  const targets = [...new Set(transitions.map((t) => `${t.to}/${t.toState}`))]
  return [
    ...targets
      .filter((target) => !table[target] && !table[screenOf(target)])
      .map((target) => `${target} is a target on the map with no entry in the screen table`),
    ...Object.keys(snapshot.screens)
      .filter((screen) => !table[screen])
      .map((screen) => `${screen} is a screen on the map with no route in the screen table`),
  ]
}

/** Every entry of the table names a route of the tree, and a state its screen set has. */
function tableProblems(snapshot: FlowSnapshot, table: ScreenTable, routes: RouteNode[]) {
  const ids = new Set(routes.map((node) => node.id))
  return Object.entries(table).flatMap(([key, { route }]) => {
    const [screen = '', state] = key.split('/')
    const set = snapshot.screens[screen]
    return [
      ...(ids.has(route) ? [] : [`${key}: ${route} is not a route in the route tree`]),
      ...(state && set && !set.states.includes(state) ? [`${key}: ${screen} has no state ${state}`] : []),
    ]
  })
}

/**
 * Every route not skipped by its shape is some screen's, and a leaf renders the screens its entries name, itself or
 * through a layout above it. A layout that renders the screen of a route below it is that screen's page.
 */
function treeProblems(table: ScreenTable, routes: RouteNode[]) {
  const byId = new Map(routes.map((node) => [node.id, node]))
  const lineage = (node: RouteNode): RouteNode[] => {
    const parent = node.parent ? byId.get(node.parent) : undefined
    return parent ? [node, ...lineage(parent)] : [node]
  }
  const parents = new Set(routes.flatMap((node) => (node.parent ? [node.parent] : [])))
  const entries = Object.entries(table).map(([key, entry]) => ({ screen: screenOf(key), node: byId.get(entry.route) }))
  return routes
    .filter((node) => !skippedByShape(node.source))
    .flatMap((node) => {
      const own = [...new Set(entries.filter((entry) => entry.node === node).map((entry) => entry.screen))]
      const isPageOfBelow = entries.some(
        (entry) =>
          entry.node && entry.node !== node && lineage(entry.node).includes(node) && renders(node, entry.screen),
      )
      if (own.length === 0 && !isPageOfBelow) return [`${node.file} is a route but no screen in the screen table`]
      if (parents.has(node.id)) return []
      return own
        .filter((screen) => !lineage(node).some((ancestor) => renders(ancestor, screen)))
        .map((screen) => `${node.file} does not render ${screen}, its screen in the screen table`)
    })
}

/** As JSX (`<AddressBook />`) or as the route's component itself (`component: PaymentMethodsBook`). */
const renders = (node: RouteNode, screen: string) =>
  new RegExp(`<${screen}[\\s/>]|\\bcomponent:\\s*${screen}\\b`).test(node.source)

/** A route that is no screen's by its shape: it renders only an Outlet, or has no component and redirects. */
function skippedByShape(source: string) {
  if (/\bcomponent:\s*\(\)\s*=>\s*<Outlet\s*\/>/.test(source)) return true
  return !/\bcomponent:/.test(source) && /\bbeforeLoad\b/.test(source) && /\bredirect\(/.test(source)
}

const screenOf = (key: string) => key.split('/')[0] ?? key

const sorted = <T>(record: Record<string, T>) =>
  Object.fromEntries(Object.entries(record).sort(([a], [b]) => a.localeCompare(b)))

/** A TS object literal, one key per line (`{}` when empty), at `depth` levels of two spaces. */
function objectLiteral<T>(record: Record<string, T>, value: (item: T) => string, depth = 1): string {
  const entries = Object.entries(record)
  if (entries.length === 0) return '{}'
  const pad = '  '.repeat(depth)
  return `{\n${entries.map(([key, item]) => `${pad}${keyLiteral(key)}: ${value(item)},`).join('\n')}\n${'  '.repeat(depth - 1)}}`
}

function entryLiteral(entry: Entry) {
  const fields = Object.entries(entry).map(([key, value]) => `${key}: ${quote(String(value))}`)
  return `{ ${fields.join(', ')} }`
}

const keyLiteral = (key: string) => (/^[A-Za-z_$][\w$]*$/.test(key) ? key : quote(key))
const quote = (text: string) => `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
