import { describe, expect, it } from 'vitest'

import { buildFlow, type RouteNode, routeProblems, type ScreenTable } from '../flow/build.ts'
import type { FlowSnapshot } from '../flow/snapshot.ts'

type FlowTransition = FlowSnapshot['flows'][number]['transitions'][number]

function transition(event: string, from: string, to: string, condition = ''): FlowTransition {
  const [fromScreen = '', fromState = ''] = from.split('/')
  const [toScreen = '', toState = ''] = to.split('/')
  return { event, from: fromScreen, fromState, to: toScreen, toState, condition }
}

const snapshot: FlowSnapshot = {
  screens: {
    Root: { page: 'flows', states: ['default', 'bag'] },
    ProductListPage: { page: 'app/browse', states: ['default', 'category'] },
    ProductDetail: { page: 'app/browse', states: ['default'] },
    AddressBook: { page: 'app/account', states: ['default', 'addressEdit'] },
  },
  flows: [
    {
      name: 'Browse → Product',
      transitions: [
        transition('PRODUCT', 'ProductListPage/default', 'ProductDetail/default'),
        // The same state drawn twice on the map is one transition.
        transition('PRODUCT', 'ProductListPage/default', 'ProductDetail/default'),
        // Drawn to `./state`: it stays on whichever route shows the screen and changes its search, so one screen
        // covers the home page, a category and a collection.
        transition('FILTER', 'ProductListPage/category', './category', "a filter's chip"),
        transition('OPEN_BAG', 'Root/default', 'Root/bag'),
      ],
    },
    {
      name: 'Addresses',
      transitions: [
        transition('EDIT_ADDRESS', 'AddressBook/default', 'AddressBook/addressEdit'),
        transition('SAVE', 'AddressBook/addressEdit', 'AddressBook/default'),
      ],
    },
  ],
}

describe('flow', () => {
  it('generates, per screen and event, the transitions drawn on the map, and the states of each screen set', () => {
    expect(buildFlow(snapshot)).toBe(
      [
        '// Generated by @proteus/design from the FigCraft `flows` page. Do not edit: change the design file, then run flow:export.',
        '// Per screen, per event: the transitions drawn on the map (from state, target screen and state, condition).',
        '',
        '/** @public The states of each screen set: the variants a screen shows. */',
        'export const screenStates = {',
        "  AddressBook: ['default', 'addressEdit'],",
        "  ProductDetail: ['default'],",
        "  ProductListPage: ['default', 'category'],",
        "  Root: ['default', 'bag'],",
        '} as const',
        '',
        'export const flow = {',
        '  AddressBook: {',
        "    EDIT_ADDRESS: [{ from: 'default', to: 'AddressBook', state: 'addressEdit' }],",
        "    SAVE: [{ from: 'addressEdit', to: 'AddressBook', state: 'default' }],",
        '  },',
        '  ProductListPage: {',
        "    FILTER: [{ from: 'category', to: '.', state: 'category', condition: 'a filter\\'s chip' }],",
        "    PRODUCT: [{ from: 'default', to: 'ProductDetail', state: 'default' }],",
        '  },',
        '  Root: {',
        "    OPEN_BAG: [{ from: 'default', to: 'Root', state: 'bag' }],",
        '  },',
        '} as const',
        '',
      ].join('\n'),
    )
  })

  it('generates an empty but valid map when the design file has no flows page', () => {
    expect(buildFlow({ screens: {}, flows: [] })).toContain(
      ['export const screenStates = {} as const', '', 'export const flow = {} as const', ''].join('\n'),
    )
  })

  it('stops when a transition names a screen set or a state the design file does not have', () => {
    const broken: FlowSnapshot = {
      screens: snapshot.screens,
      flows: [
        {
          name: 'Checkout',
          transitions: [
            transition('CHECKOUT', 'Root/bag', 'Checkout/default'),
            transition('CLOSE', 'Root/menu', 'Root/default'),
            // `.` is the screen it is drawn from, so its state is that screen's.
            transition('SORT', 'ProductDetail/default', './sorted'),
          ],
        },
      ],
    }
    expect(() => buildFlow(broken)).toThrow(
      "flows can't be generated:\n  Checkout: Checkout is not a screen set\n  Checkout: Root has no state menu\n  Checkout: ProductDetail has no state sorted",
    )
  })
})

const route = (id: string, parent: string | undefined, file: string, source: string): RouteNode => ({
  id,
  parent,
  file: `src/routes/${file}`,
  source,
})

/** A store-shaped tree: layouts that render only an Outlet, a redirect, a layout that is the page, and drawer leaves. */
const routes: RouteNode[] = [
  route(
    '__root__',
    undefined,
    '__root.tsx',
    'component: RootComponent\nfunction RootComponent() { return <><Toaster /><Outlet /></> }',
  ),
  route(
    '/_main',
    '__root__',
    '_main/route.tsx',
    'component: MainLayout\nfunction MainLayout() { return <><Header /><Outlet /></> }',
  ),
  route('/_main/', '/_main', '_main/index.tsx', 'component: () => <ProductListPage heading="All products" />'),
  route(
    '/_main/categories/$handle',
    '/_main',
    '_main/categories/$handle.tsx',
    'component: CategoryPage\nfunction CategoryPage() { return <ProductListPage /> }',
  ),
  // Skipped by its shape: a layout whose component renders only <Outlet />, so it is no screen's.
  route('/_main/products', '/_main', '_main/products/route.tsx', 'ssr: true,\n  component: () => <Outlet />,'),
  route(
    '/_main/products/$handle',
    '/_main/products',
    '_main/products/$handle.tsx',
    // Rendered by reference rather than as JSX.
    'component: ProductDetail,',
  ),
  // Skipped by its shape: no component, and a redirect in beforeLoad.
  route(
    '/_main/_authed',
    '/_main',
    '_main/_authed/route.tsx',
    "beforeLoad: () => {\n    if (!isRegistered()) throw redirect({ to: '/login' })\n  },",
  ),
  // A layout that is the page: it renders the screen, and its leaves are the screen and its drawer states.
  route(
    '/_main/_authed/addresses',
    '/_main/_authed',
    '_main/_authed/addresses/route.tsx',
    'component: () => (<><AddressBook /><Outlet /></>)',
  ),
  route(
    '/_main/_authed/addresses/',
    '/_main/_authed/addresses',
    '_main/_authed/addresses/index.tsx',
    'component: () => null',
  ),
  route(
    '/_main/_authed/addresses/$addressId/edit',
    '/_main/_authed/addresses',
    '_main/_authed/addresses/$addressId/edit.tsx',
    'component: () => <UpdateAddressForm />',
  ),
]

const table: ScreenTable = {
  NotFound: { route: '__root__' },
  Root: { route: '/_main' },
  'Root/bag': { route: '/_main' },
  ProductListPage: { route: '/_main/' },
  'ProductListPage/category': { route: '/_main/categories/$handle' },
  ProductDetail: { route: '/_main/products/$handle' },
  AddressBook: { route: '/_main/_authed/addresses/' },
  'AddressBook/addressEdit': { route: '/_main/_authed/addresses/$addressId/edit' },
}

describe('check:flow', () => {
  it('passes when every target is in the screen table, every screen has a route and every route renders its screen', () => {
    expect(routeProblems(snapshot, table, routes)).toEqual([])
  })

  it('fails on a missing target, a screen with no route, and a route that does not render its own screen', () => {
    const drawn: FlowSnapshot = {
      screens: { ...snapshot.screens, OrderContent: { page: 'app/account', states: ['default'] } },
      flows: [
        ...snapshot.flows,
        {
          name: 'Orders',
          transitions: [
            transition('ORDER', 'AddressBook/default', 'OrderContent/default'),
            transition('BACK', 'OrderContent/default', 'AddressBook/default'),
          ],
        },
      ],
    }
    const { ProductListPage: _, ...withoutHome } = table
    const brokenTable: ScreenTable = {
      ...withoutHome,
      // Points at a route the tree doesn't have.
      'Root/bag': { route: '/_main/bag' },
      // Names a state the screen set doesn't have.
      'ProductDetail/zoomed': { route: '/_main/products/$handle' },
    }
    const brokenRoutes = [
      ...routes.filter((node) => node.id !== '/_main/products/$handle'),
      // Renders another screen than the one its table entry names.
      route(
        '/_main/products/$handle',
        '/_main/products',
        '_main/products/$handle.tsx',
        'component: () => <ProductError />',
      ),
      // A layout that renders more than an Outlet is checked like any route.
      route(
        '/_auth',
        '__root__',
        '_auth/route.tsx',
        'component: () => (<><Link to="/">Continue shopping</Link><Outlet /></>)',
      ),
    ]

    expect(routeProblems(drawn, brokenTable, brokenRoutes)).toEqual([
      'OrderContent/default is a target on the map with no entry in the screen table',
      'ProductListPage is a screen on the map with no route in the screen table',
      'OrderContent is a screen on the map with no route in the screen table',
      'Root/bag: /_main/bag is not a route in the route tree',
      'ProductDetail/zoomed: ProductDetail has no state zoomed',
      'src/routes/_main/index.tsx is a route but no screen in the screen table',
      'src/routes/_main/products/$handle.tsx does not render ProductDetail, its screen in the screen table',
      'src/routes/_auth/route.tsx is a route but no screen in the screen table',
    ])
  })

  it('reports nothing to check while the design file has no flows page', () => {
    expect(routeProblems({ screens: {}, flows: [] }, {}, routes)).toEqual([])
  })
})
