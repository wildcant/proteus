import { describe, expect, it } from 'vitest'

import { buildIcons } from '../icons/build.ts'

const OUTPUT = '/shop/src/components/ui/icon/icon.glyphs.tsx'

// What FigCraft's `export --format svg` writes for a variant clipped to its 24 × 24 frame.
const frameClip = (id: string) => `<defs><clipPath id="${id}"><path d="M0 0L24 0L24 24L0 24Z"/></clipPath></defs>`
const svg = (body: string, viewBox = '0 0 24 24') =>
  `<svg width="24" height="24" viewBox="${viewBox}" fill="none" xmlns="http://www.w3.org/2000/svg">${body}</svg>`

const plus = svg(
  `<g><g clip-path="url(#clip1)"><path transform="matrix(1 0 0 1 5 5)" d="M7 0L7 14M0 7L14 7" fill="none" stroke="#0D1012" stroke-width="1.5" stroke-linecap="square"/></g></g>${frameClip('clip1')}`,
)

// Two shapes and a clip of its own, which must not collide with another glyph's on the same page.
const search = svg(
  `<g clip-path="url(#clip2)"><circle cx="10" cy="10" r="6" stroke="#0D1012" stroke-width="1.5"/><path d="M15 15L20 20" stroke="#0D1012" stroke-width="1.5" fill-rule="evenodd"/></g><defs><clipPath id="clip2"><rect x="2" y="2" width="20" height="20"/></clipPath></defs>`,
)

describe('icons', () => {
  it('turns each Icon variant into the inside of a 24 × 24 svg, drawn in currentColor, keyed by its name', () => {
    const files = buildIcons(
      new Map([
        ['search', search],
        ['plus', plus],
      ]),
      { set: 'Icon', output: OUTPUT },
    )

    expect([...files.keys()]).toEqual([OUTPUT])
    expect(files.get(OUTPUT)).toBe(
      [
        '// Generated by @proteus/design from the FigCraft component set "Icon". Do not edit: change the design file, then run icons:export.',
        "// Each glyph is the inside of a 24 × 24 <svg>; icon.tsx draws the frame, and its text colour is the glyph's (currentColor).",
        '',
        'export const glyphs = {',
        '  plus: (',
        '    <path transform="matrix(1 0 0 1 5 5)" d="M7 0L7 14M0 7L14 7" fill="none" stroke="currentColor" strokeWidth="1.5" strokeLinecap="square" />',
        '  ),',
        '  search: (',
        '    <>',
        '      <g clipPath="url(#search-clip2)">',
        '        <circle cx="10" cy="10" r="6" stroke="currentColor" strokeWidth="1.5" />',
        '        <path d="M15 15L20 20" stroke="currentColor" strokeWidth="1.5" fillRule="evenodd" />',
        '      </g>',
        '      <defs>',
        '        <clipPath id="search-clip2">',
        '          <rect x="2" y="2" width="20" height="20" />',
        '        </clipPath>',
        '      </defs>',
        '    </>',
        '  ),',
        '}',
        '',
        "/** A glyph of the design file's Icon set: the `name` prop of the store's Icon. */",
        'export type IconName = keyof typeof glyphs',
        '',
      ].join('\n'),
    )
  })

  it('generates no file while the design file has no Icon set', () => {
    expect(buildIcons(new Map(), { set: 'Icon', output: OUTPUT }).size).toBe(0)
  })

  it('stops on a glyph that is not one colour on a 24 × 24 frame, or uses an element it cannot map', () => {
    const glyphs = new Map([
      ['wide', svg('<path d="M0 0L30 0" stroke="#0D1012"/>', '0 0 30 24')],
      ['two-tone', svg('<path d="M0 0L1 1" stroke="#0D1012"/><path d="M1 1L2 2" stroke="#FF0000"/>')],
      ['label', svg('<text x="0" y="0">A</text>')],
    ])
    expect(() => buildIcons(glyphs, { set: 'Icon', output: OUTPUT })).toThrow(
      [
        "Icon can't be generated:",
        '  label: <text> is not an svg element a glyph may use',
        '  two-tone: 2 colours (#0D1012, #FF0000); a glyph is one colour',
        '  wide: viewBox 0 0 30 24, not 0 0 24 24 (clip the variant to its frame in FigCraft)',
      ].join('\n'),
    )
  })
})
